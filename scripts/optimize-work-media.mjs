import { createClient } from '@supabase/supabase-js';
import { mkdtemp, readFile, stat } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
const run = promisify(execFile);
const admin = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false } });
const { data: rows, error } = await admin.from('works').select('id,title,video_key,poster_key,file_size').eq('published', true);
if (error) throw error;
for (const row of rows) {
  if (row.poster_key) continue; // Preserve custom covers and already-completed derivatives.
  const dir = await mkdtemp(join(tmpdir(), 'bottopia-media-'));
  const { data: source, error: downloadError } = await admin.storage.from('works').download(row.video_key);
  if (downloadError) throw downloadError;
  // Media outputs are generated by ffmpeg, not source-code edits.
  const { writeFile } = await import('node:fs/promises');
  const input = join(dir, 'source.mp4');
  await writeFile(input, Buffer.from(await source.arrayBuffer()));
  const prefix = `optimized/${row.id}/v1`;
  const outputs = [
    ['poster.jpg', ['-ss', '0.5', '-i', input, '-frames:v', '1', '-vf', 'scale=960:-2', '-q:v', '3'], 'image/jpeg'],
    ['preview.mp4', ['-i', input, '-t', '6', '-an', '-vf', 'scale=640:-2,fps=20', '-c:v', 'libx264', '-preset', 'fast', '-crf', '28', '-pix_fmt', 'yuv420p', '-movflags', '+faststart'], 'video/mp4'],
    ['playback.mp4', ['-i', input, '-c', 'copy', '-movflags', '+faststart'], 'video/mp4'],
  ];
  for (const [name, args, contentType] of outputs) {
    const path = join(dir, name);
    await run('ffmpeg', ['-hide_banner', '-loglevel', 'error', ...args, path]);
    const { error: uploadError } = await admin.storage.from('works').upload(`${prefix}/${name}`, await readFile(path), { contentType, cacheControl: '3600', upsert: true });
    if (uploadError) throw uploadError;
    console.log(JSON.stringify({ title: row.title, variant: name, bytes: (await stat(path)).size, originalBytes: row.file_size }));
  }
  // Compare-and-set prevents overwriting a cover changed while processing.
  let update = admin.from('works').update({ poster_key: `${prefix}/poster.jpg` }).eq('id', row.id).eq('video_key', row.video_key);
  update = row.poster_key ? update.eq('poster_key', row.poster_key) : update.is('poster_key', null);
  const { error: updateError } = await update;
  if (updateError) throw updateError;
  console.log(`Activated ${row.id}; original retained; working files: ${dir}`);
}
